// Runs before every deploy (see "build" in wrangler.jsonc). Writes src/stamp.js with a short
// hash of each stylesheet and script the Worker-rendered pages load, so their URLs change
// whenever the file does and no browser or edge cache can serve a stale copy.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const files = ['style.css', 'admin.css', 'admin.js', 'wind.js', 'analytics.js'];
const stamps = {};
for (const f of files) stamps[f] = createHash('sha256').update(readFileSync(new URL(`../public/${f}`, import.meta.url))).digest('hex').slice(0, 8);

mkdirSync(new URL('../src/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/stamp.js', import.meta.url), `// Generated by scripts/stamp.mjs before each deploy. Do not edit.\nexport const STAMP = ${JSON.stringify(stamps, null, 2)};\n`);
console.log('stamped', Object.entries(stamps).map(([k, v]) => `${k}=${v}`).join(' '));
